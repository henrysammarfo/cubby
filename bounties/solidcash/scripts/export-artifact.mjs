// Copies the compiled CubbyAllowance artifact into the app source tree so the web app needs no SolidCash runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const artifact = JSON.parse(readFileSync(new URL('../artifacts/solidcash/CubbyAllowance.json', import.meta.url), 'utf8'));
const hex = execFileSync('npx', ['solidc', 'contracts/CubbyAllowance.scash', '-h'], { cwd: new URL('..', import.meta.url).pathname }).toString().trim();
const selectors = Object.fromEntries(artifact.abi.map((f) => [f.name, f.selector]));
const out = `// Generated by bounties/solidcash/scripts/export-artifact.mjs from contracts/CubbyAllowance.scash. Do not edit.
export const ALLOWANCE_COMPILER = ${JSON.stringify(artifact.compiler.name + ' ' + artifact.compiler.version)};
export const ALLOWANCE_BYTECODE_HEX = ${JSON.stringify(hex)};
export const ALLOWANCE_SELECTORS = ${JSON.stringify(selectors)} as const;
export const ALLOWANCE_SOURCE = ${JSON.stringify(artifact.source)};
`;
writeFileSync(new URL('../../../src/bounties/allowance-artifact.ts', import.meta.url), out);
console.log('wrote src/bounties/allowance-artifact.ts', hex.length / 2, 'bytes', selectors);
